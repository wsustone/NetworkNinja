//! Plain-language explanations of findings, for the people fixing an
//! exercise: what a finding means, why it matters to the other simulations,
//! what usually causes it and how to fix it. Keyed by rule name and finding
//! type (`Alert::rule.name()`, `Alert::kind`); served at `/api/explain`.

/// One finding, explained for exercise integrators.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Explanation {
    pub rule: &'static str,
    pub kind: &'static str,
    /// A short headline: what went wrong, in plain words.
    pub title: &'static str,
    /// Why it matters: what the other simulations see or get wrong.
    pub impact: &'static str,
    /// What usually causes it.
    pub causes: &'static str,
    /// What to change, and where.
    pub fix: &'static str,
}

const fn x(
    rule: &'static str,
    kind: &'static str,
    title: &'static str,
    impact: &'static str,
    causes: &'static str,
    fix: &'static str,
) -> Explanation {
    Explanation {
        rule,
        kind,
        title,
        impact,
        causes,
        fix,
    }
}

