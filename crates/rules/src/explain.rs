/// Every explanation.
pub fn catalog() -> &'static [Explanation] {
    CATALOG
}

/// The explanation of a finding, by rule name and finding type; a rule's
/// `*` entry covers every finding type it has (the heartbeat rule's are PDU
/// types).
pub fn explain(rule: &str, kind: &str) -> Option<&'static Explanation> {
    let find = |k: &str| CATALOG.iter().find(|e| e.rule == rule && e.kind == k);
    find(kind).or_else(|| find("*"))
}
